import os
import glob
import math

import torch
import numpy as np
import matplotlib.pyplot as plt
import librosa


BASE_DIR = ("/scratch/elec/t412-techpsychoacoustics/msc-thesis/2026_fstaub/staubf1/Projects/Master_Thesis/data/harp/R4000_P8_S3_Order3_24kHz_shoeBox_rtProfilesMIT_ISMOrder30/hopiv_accdoa_mel128_TIMIT_babble_full")
#BASE_DIR = ("/scratch/elec/t412-techpsychoacoustics/msc-thesis/2026_fstaub/staubf1/Projects/Master_Thesis/data/arni_em32/sh_wavs/hopiv_accdoa_mel128_TIMIT_babble")

PT_DIR = os.path.join(BASE_DIR, "pt/normalized")
PNG_DIR = os.path.join(BASE_DIR, "png")

os.makedirs(PNG_DIR, exist_ok=True)

BATCH_INDEX = 0
ROOM_INDEX = 0
SAMPLE_INDEX = 1

# Number of subplot columns in the saved figure.
SUBPLOT_COLUMNS = 10


def to_numpy(x):
    if isinstance(x, torch.Tensor):
        return x.detach().cpu().numpy()

    return np.asarray(x)


def find_pt_files(pt_dir):
    """
    Find PT batch files generated by either the current or older naming scheme.
    """
    patterns = [
        "room_*.pt",          # current generator: room_0000-0099.pt
        "rooms_batch*.pt",    # older generator
        "*.pt",               # fallback
    ]

    for pattern in patterns:
        files = sorted(glob.glob(os.path.join(pt_dir, pattern)))

        if files:
            print(f"Using PT filename pattern: {pattern}")
            return files

    return []


if not os.path.isdir(PT_DIR):
    raise FileNotFoundError(
        f"PT directory does not exist:\n{PT_DIR}\n\n"
        f"Check BASE_DIR or confirm that dataset generation completed."
    )

pt_files = find_pt_files(PT_DIR)

if not pt_files:
    directory_contents = sorted(os.listdir(PT_DIR))

    raise FileNotFoundError(
        f"No .pt files found in:\n{PT_DIR}\n\n"
        f"Directory contents:\n{directory_contents}"
    )

if not 0 <= BATCH_INDEX < len(pt_files):
    raise IndexError(
        f"BATCH_INDEX={BATCH_INDEX} is out of range. "
        f"Found {len(pt_files)} PT files."
    )

pt_path = pt_files[BATCH_INDEX]

print("Loading:")
print(pt_path)

# weights_only=False is needed because the file contains nested Python
# dictionaries and metadata, not only tensor weights.
try:
    batch = torch.load(
        pt_path,
        map_location="cpu",
        weights_only=False,
    )
except TypeError:
    # Compatibility with older PyTorch versions without weights_only.
    batch = torch.load(
        pt_path,
        map_location="cpu",
    )

if not isinstance(batch, dict):
    raise TypeError(
        f"Expected the PT file to contain a dictionary, "
        f"but got {type(batch).__name__}."
    )

if "samples" not in batch:
    raise KeyError(
        f"PT file does not contain a top-level 'samples' key. "
        f"Available keys: {list(batch.keys())}"
    )

rooms = batch["samples"]

if not 0 <= ROOM_INDEX < len(rooms):
    raise IndexError(
        f"ROOM_INDEX={ROOM_INDEX} is out of range. "
        f"Batch contains {len(rooms)} rooms."
    )

room_record = rooms[ROOM_INDEX]

if "samples" not in room_record:
    raise KeyError(
        f"Selected room does not contain a 'samples' key. "
        f"Available keys: {list(room_record.keys())}"
    )

samples = room_record["samples"]

if not 0 <= SAMPLE_INDEX < len(samples):
    raise IndexError(
        f"SAMPLE_INDEX={SAMPLE_INDEX} is out of range. "
        f"Room contains {len(samples)} samples."
    )

sample = samples[SAMPLE_INDEX]

if "X" not in sample:
    raise KeyError(
        f"Selected sample does not contain 'X'. "
        f"Available keys: {list(sample.keys())}"
    )

X = to_numpy(sample["X"])

print("\nTop-level keys:")
print(list(batch.keys()))

print("\nSelected room:")
print("room:", room_record.get("room"))
print("num_samples in room:", room_record.get("num_samples"))
print("actual samples:", len(samples))

print("\nSelected sample:")
print("sample_id:", sample.get("sample_id"))
print("segment_idx:", sample.get("segment_idx"))
print("sample_rate:", sample.get("sample_rate"))
print("feature:", sample.get("feature"))
print("num_mel_bins:", sample.get("num_mel_bins"))
print("num_feature_channels:", sample.get("num_feature_channels"))
print("n_fft:", sample.get("n_fft"))
print("hop_length:", sample.get("hop_length"))

print("\nShape:")
print("X shape:", X.shape)

if X.ndim != 3:
    raise ValueError(
        f"Expected X with shape (time, mel bins, feature channels), "
        f"got {X.shape}."
    )

num_time_frames, actual_num_mel_bins, num_channels = X.shape

sample_rate = int(sample.get("sample_rate", 16000))
n_fft = int(sample.get("n_fft", 1024))
hop_length = int(sample.get("hop_length", n_fft // 4))
num_mel_bins = int(
    sample.get("num_mel_bins", actual_num_mel_bins)
)

if num_mel_bins != actual_num_mel_bins:
    print(
        f"Warning: metadata says {num_mel_bins} mel bins, "
        f"but X contains {actual_num_mel_bins}. "
        f"Using X.shape[1]."
    )
    num_mel_bins = actual_num_mel_bins

metadata_num_channels = sample.get("num_feature_channels")

if (
    metadata_num_channels is not None
    and int(metadata_num_channels) != num_channels
):
    print(
        f"Warning: metadata says {metadata_num_channels} channels, "
        f"but X contains {num_channels}. Using X.shape[2]."
    )

# Approximate center frequency of every mel bin.
mel_frequencies = librosa.mel_frequencies(
    n_mels=num_mel_bins,
    fmin=0.0,
    fmax=sample_rate / 2.0,
)

# Time in seconds for every feature frame.
frame_times = librosa.frames_to_time(
    np.arange(num_time_frames),
    sr=sample_rate,
    hop_length=hop_length,
    n_fft=n_fft,
)

room_id = int(room_record.get("room", ROOM_INDEX))
sample_id = str(sample.get("sample_id", f"room{room_id}"))
segment_idx = int(sample.get("segment_idx", SAMPLE_INDEX))

safe_sample_id = (
    sample_id
    .replace(os.sep, "_")
    .replace(" ", "_")
)

file_prefix = (
    f"batch{BATCH_INDEX:04d}_"
    f"room{room_id:04d}_"
    f"{safe_sample_id}_"
    f"segment{segment_idx:04d}"
)

num_columns = min(SUBPLOT_COLUMNS, num_channels)
num_rows = math.ceil(num_channels / num_columns)

fig, axes = plt.subplots(
    num_rows,
    num_columns,
    figsize=(7 * num_columns, 4.5 * num_rows),
    sharex=True,
    sharey=True,
    squeeze=False,
)

# Use one common colour scale so values are comparable across channels.
color_min = np.nanmin(X)
color_max = np.nanmax(X)

if not np.isfinite(color_min) or not np.isfinite(color_max):
    raise ValueError(
        "X contains no finite values that can be plotted."
    )

# Avoid an invalid colour range when all values are identical.
if color_min == color_max:
    color_min -= 1e-6
    color_max += 1e-6

images = []

for channel_idx in range(num_channels):
    row_idx = channel_idx // num_columns
    column_idx = channel_idx % num_columns
    ax = axes[row_idx, column_idx]

    # X[:, :, channel] has shape (time, mel).
    # imshow expects the first dimension along y, so transpose to
    # shape (mel, time).
    channel_data = X[:, :, channel_idx].T

    image = ax.imshow(
        channel_data,
        origin="lower",
        aspect="auto",
        interpolation="none",
        extent=[
            frame_times[0],
            frame_times[-1],
            mel_frequencies[0],
            mel_frequencies[-1],
        ],
        vmin=color_min,
        vmax=color_max,
    )

    images.append(image)

    ax.set_title(f"Feature channel {channel_idx}")
    ax.set_xlabel("Time [s]")
    ax.set_ylabel("Approximate mel-bin center frequency [Hz]")

# Hide unused subplot positions.
for unused_idx in range(num_channels, num_rows * num_columns):
    row_idx = unused_idx // num_columns
    column_idx = unused_idx % num_columns
    axes[row_idx, column_idx].set_visible(False)

fig.suptitle(
    f"All feature channels\n"
    f"{sample_id}, segment {segment_idx}, X shape {X.shape}",
    fontsize=14,
)

# One shared colour bar for all channel subplots.
visible_axes = [
    ax
    for ax_row in axes
    for ax in ax_row
    if ax.get_visible()
]

fig.colorbar(
    images[0],
    ax=visible_axes,
    label="Standardized feature value",
    fraction=0.025,
    pad=0.02,
)

fig.subplots_adjust(
    top=0.90,
    bottom=0.08,
    left=0.08,
    right=0.92,
    hspace=0.30,
    wspace=0.20,
)

png_path = os.path.join(
    PNG_DIR,
    f"{file_prefix}_all_feature_channels.png",
)

fig.savefig(
    png_path,
    dpi=200,
    bbox_inches="tight",
)

plt.close(fig)

print("\nSaved PNG:")
print(png_path)