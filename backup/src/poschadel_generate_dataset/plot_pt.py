def to_numpy(x):
    if isinstance(x, torch.Tensor):
        return x.detach().cpu().numpy()

    return np.asarray(x)


def find_pt_files(pt_dir):
    """
    Find PT batch files generated by the tensor-only dataset generator.
    """
    patterns = [
        "room_*.pt",
        "rooms_batch*.pt",
        "*.pt",
    ]

    for pattern in patterns:
        files = sorted(glob.glob(os.path.join(pt_dir, pattern)))

        if files:
            print(f"Using PT filename pattern: {pattern}")
            return files

    return []


def load_tensor_batch(pt_path):
    """
    Load a tensor-only PT file.

    Expected file content:
        (X, accdoa)

    Expected shapes:
        X:
            (num_samples, time_frames, mel_bins, feature_channels)

        accdoa:
            (num_samples, time_frames, num_speakers, 3)
    """
    try:
        loaded = torch.load(
            pt_path,
            map_location="cpu",
            weights_only=False,
        )
    except TypeError:
        loaded = torch.load(
            pt_path,
            map_location="cpu",
        )

    if not isinstance(loaded, (tuple, list)):
        raise TypeError(
            "Expected the PT file to contain a tuple or list "
            f"(X, accdoa), but got {type(loaded).__name__}."
        )

    if len(loaded) != 2:
        raise ValueError(
            "Expected exactly two entries in the PT file: "
            f"(X, accdoa). Got {len(loaded)} entries."
        )

    X_batch, accdoa_batch = loaded

    if not isinstance(X_batch, torch.Tensor):
        raise TypeError(
            "Expected X to be a torch.Tensor, but got "
            f"{type(X_batch).__name__}."
        )

    if not isinstance(accdoa_batch, torch.Tensor):
        raise TypeError(
            "Expected accdoa to be a torch.Tensor, but got "
            f"{type(accdoa_batch).__name__}."
        )

    if X_batch.ndim != 4:
        raise ValueError(
            "Expected X batch with shape "
            "(samples, time, mel bins, feature channels), "
            f"but got {tuple(X_batch.shape)}."
        )

    if accdoa_batch.ndim != 4:
        raise ValueError(
            "Expected ACCDOA batch with shape "
            "(samples, time, speakers, xyz), "
            f"but got {tuple(accdoa_batch.shape)}."
        )

    if X_batch.shape[0] != accdoa_batch.shape[0]:
        raise ValueError(
            "X and ACCDOA contain different numbers of samples: "
            f"{X_batch.shape[0]} and {accdoa_batch.shape[0]}."
        )

    if X_batch.shape[1] != accdoa_batch.shape[1]:
        raise ValueError(
            "X and ACCDOA contain different numbers of time frames: "
            f"{X_batch.shape[1]} and {accdoa_batch.shape[1]}."
        )

    if accdoa_batch.shape[-1] != 3:
        raise ValueError(
            "Expected the last ACCDOA dimension to contain x, y, z, "
            f"but got shape {tuple(accdoa_batch.shape)}."
        )

    return X_batch, accdoa_batch


def make_time_axis(num_time_frames, sample_rate, hop_length):
    """
    Return the nominal start time of every feature frame.

    This matches the custom STFT generator, where frame i starts at
    i * hop_length.
    """
    return (
        np.arange(num_time_frames, dtype=np.float32)
        * float(hop_length)
        / float(sample_rate)
    )


def make_mel_frequency_axis(
    num_mel_bins,
    sample_rate,
):
    """
    Approximate center frequency of every mel bin.
    """
    return librosa.mel_frequencies(
        n_mels=num_mel_bins,
        fmin=0.0,
        fmax=sample_rate / 2.0,
    )


def plot_feature_channels(
    X,
    frame_times,
    mel_frequencies,
    output_path,
    title,
):
    """
    Plot all feature channels using one shared colour scale.

    X shape:
        (time_frames, mel_bins, feature_channels)
    """
    if X.ndim != 3:
        raise ValueError(
            "Expected one X sample with shape "
            "(time, mel bins, feature channels), "
            f"but got {X.shape}."
        )

    num_time_frames, num_mel_bins, num_channels = X.shape

    num_columns = min(SUBPLOT_COLUMNS, num_channels)
    num_rows = math.ceil(num_channels / num_columns)

    fig, axes = plt.subplots(
        num_rows,
        num_columns,
        figsize=(5.5 * num_columns, 4.0 * num_rows),
        sharex=True,
        sharey=True,
        squeeze=False,
    )

    color_min = float(np.nanmin(X))
    color_max = float(np.nanmax(X))

    if not np.isfinite(color_min) or not np.isfinite(color_max):
        raise ValueError(
            "X contains no finite values that can be plotted."
        )

    if color_min == color_max:
        color_min -= 1e-6
        color_max += 1e-6

    # Build pixel-edge coordinates so the complete first and last
    # frames are represented correctly.
    time_step = (
        float(HOP_LENGTH) / float(SAMPLE_RATE)
        if num_time_frames > 1
        else 1.0
    )

    time_min = frame_times[0]
    time_max = frame_times[-1] + time_step

    frequency_min = 0.0
    frequency_max = SAMPLE_RATE / 2.0

    first_image = None

    for channel_idx in range(num_channels):
        row_idx = channel_idx // num_columns
        column_idx = channel_idx % num_columns
        ax = axes[row_idx, column_idx]

        # X[:, :, channel] is (time, mel).
        # imshow expects (vertical, horizontal), hence transpose.
        channel_data = X[:, :, channel_idx].T

        image = ax.imshow(
            channel_data,
            origin="lower",
            aspect="auto",
            interpolation="none",
            extent=[
                time_min,
                time_max,
                frequency_min,
                frequency_max,
            ],
            vmin=color_min,
            vmax=color_max,
        )

        if first_image is None:
            first_image = image

        ax.set_title(f"Feature channel {channel_idx}")
        ax.set_xlabel("Time [s]")
        ax.set_ylabel("Approx. mel frequency [Hz]")

    for unused_idx in range(
        num_channels,
        num_rows * num_columns,
    ):
        row_idx = unused_idx // num_columns
        column_idx = unused_idx % num_columns
        axes[row_idx, column_idx].set_visible(False)

    visible_axes = [
        ax
        for ax_row in axes
        for ax in ax_row
        if ax.get_visible()
    ]

    fig.suptitle(title, fontsize=14)

    fig.colorbar(
        first_image,
        ax=visible_axes,
        label="Feature value",
        fraction=0.025,
        pad=0.02,
    )

    fig.subplots_adjust(
        top=0.92,
        bottom=0.08,
        left=0.07,
        right=0.93,
        hspace=0.32,
        wspace=0.20,
    )

    fig.savefig(
        output_path,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)


def plot_accdoa(
    accdoa,
    frame_times,
    output_path,
    title,
):
    """
    Plot ACCDOA x/y/z components and vector magnitude for each speaker.

    accdoa shape:
        (time_frames, num_speakers, 3)
    """
    if accdoa.ndim != 3:
        raise ValueError(
            "Expected one ACCDOA sample with shape "
            "(time, speakers, 3), "
            f"but got {accdoa.shape}."
        )

    if accdoa.shape[-1] != 3:
        raise ValueError(
            "Expected the final ACCDOA dimension to have size 3, "
            f"but got {accdoa.shape}."
        )

    num_time_frames, num_speakers, _ = accdoa.shape

    fig, axes = plt.subplots(
        num_speakers,
        1,
        figsize=(14, 3.5 * num_speakers),
        sharex=True,
        squeeze=False,
    )

    component_names = ("x", "y", "z")

    for speaker_idx in range(num_speakers):
        ax = axes[speaker_idx, 0]

        speaker_accdoa = accdoa[:, speaker_idx, :]

        for component_idx, component_name in enumerate(
            component_names
        ):
            ax.plot(
                frame_times,
                speaker_accdoa[:, component_idx],
                marker=".",
                linewidth=1.2,
                label=component_name,
            )

        magnitude = np.linalg.norm(
            speaker_accdoa,
            axis=-1,
        )

        ax.plot(
            frame_times,
            magnitude,
            linestyle="--",
            linewidth=1.3,
            label="magnitude",
        )

        ax.axhline(
            0.0,
            linewidth=0.8,
        )

        ax.set_ylim(-1.1, 1.1)
        ax.set_ylabel("ACCDOA")
        ax.set_title(f"Speaker slot {speaker_idx}")
        ax.grid(True, alpha=0.25)
        ax.legend(loc="upper right", ncol=4)

    axes[-1, 0].set_xlabel("Time [s]")

    fig.suptitle(title, fontsize=14)
    fig.tight_layout(rect=[0.0, 0.0, 1.0, 0.96])

    fig.savefig(
        output_path,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)


